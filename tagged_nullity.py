# ==============================================================================
#  СИСТЕМА B: помеченное нулити с extract() и трассировкой
# ==============================================================================

class NullB:
    """⊥(x): объект-нулити с меткой x и историей рождения."""
    __slots__ = ("tag", "origin")

    def __init__(self, tag, origin=None):
        self.tag = tag
        self.origin = origin if origin is not None else f"{tag}/0"

    def __repr__(self):
        return f"⊥({self.tag})"

    def __eq__(self, other):
        return isinstance(other, NullB) and self.tag == other.tag


def _is_num(v):
    return isinstance(v, (int, float)) and not isinstance(v, bool)


def b_add(a, b):
    """B3, B7."""
    if isinstance(a, NullB) and isinstance(b, NullB):
        t = a.tag + b.tag
        return 0 if t == 0 else NullB(t, f"({a.origin}) + ({b.origin})")
    if isinstance(a, NullB):
        return NullB(a.tag, a.origin)          # метка замораживается
    if isinstance(b, NullB):
        return NullB(b.tag, b.origin)
    return a + b


def b_mul(a, b):
    """B4, B5."""
    if isinstance(a, NullB) and _is_num(b):
        t = a.tag * b
        return 0 if t == 0 else NullB(t, f"({a.origin})×{b}")
    if _is_num(a) and isinstance(b, NullB):
        t = a * b.tag
        return 0 if t == 0 else NullB(t, f"{a}×({b.origin})")
    if isinstance(a, NullB) and isinstance(b, NullB):
        t = a.tag * b.tag
        return 0 if t == 0 else NullB(t, f"({a.origin})×({b.origin})")
    return a * b


def b_sub(a, b):
    """Вычитание через умножение на -1 и сложение."""
    return b_add(a, b_mul(-1, b))


def b_div(a, b):
    """B1, B2, B8. Деление НА нулити не определено — сначала extract(b)."""
    if _is_num(b) and b == 0:
        if _is_num(a) and a == 0:
            return 0                                    # B2: 0/0 = 0
        if isinstance(a, NullB):
            return NullB(a.tag, f"({a.origin})/0")      # B8
        return NullB(a, f"{a}/0")                       # B1
    if isinstance(b, NullB):
        # Деление НА нулити НЕ является операцией системы: оно молча
        # «воскрешало» бы метку обычным делением (1/⊥(2) → 0.5) — в обход
        # extract() и в нарушение принципа B5/B6, согласно которому возврат
        # значения возможен только выделенной немультипликативной операцией.
        # См. открытый вопрос 1 в статье. Правильный путь — явная распаковка
        # делителя: b_div(a, extract(b)).
        raise ValueError(
            "деление на нулити не определено: сначала extract(b)"
        )
    if isinstance(a, NullB):
        # Конвенция (линейность, как в B4): ⊥(x)/b = ⊥(x/b) для b ≠ 0.
        t = a.tag / b
        return 0 if t == 0 else NullB(t, f"({a.origin})/{b}")
    return a / b


def extract(x):
    """B6: возврат изначального числа. ОТДЕЛЬНАЯ операция, не умножение."""
    return x.tag if isinstance(x, NullB) else x


def trace(x):
    """Полная родословная ошибки для отладки."""
    return x.origin if isinstance(x, NullB) else "ошибок не было"


# ==============================================================================
#  СИСТЕМА C: возврат ⊥(x)×0 = x при запрете перестановки скобок
#  (неассоциативная алгебра; выражения — деревья)
# ==============================================================================

class Node:
    """Узел дерева выражения: значение + навсегда зафиксированная структура."""
    __slots__ = ("op", "L", "R", "val", "isnull")

    def __init__(self, op, L, R, val, isnull=False):
        self.op, self.L, self.R, self.val, self.isnull = op, L, R, val, isnull

    def __repr__(self):
        if self.op == 'num':
            return str(self.val)
        return f"({self.L} {self.op} {self.R})"

    def same(self, other):
        """'Равенство' в системе C — только побитовое совпадение деревьев."""
        if self.op != other.op or self.isnull != other.isnull:
            return False
        if self.op == 'num':
            return self.val == other.val
        return self.L.same(other.L) and self.R.same(other.R)


def num(v):
    return Node('num', None, None, v)


def _nullnode(tag, L, R):
    return Node('null', L, R, tag, isnull=True)


def c_mul(A, B):
    """Возврат ⊥(x)×0 = x и 0×⊥(x) = x."""
    if A.isnull and not B.isnull and B.val == 0:
        return num(A.val)
    if B.isnull and not A.isnull and A.val == 0:
        return num(B.val)
    v = A.val * B.val
    if A.isnull or B.isnull:
        return _nullnode(v, A, B)
    return num(v)


def c_div(A, B):
    if not B.isnull and B.val == 0:
        if not A.isnull and A.val == 0:
            return num(0)
        return _nullnode(A.val, A, B)
    return num(A.val / B.val)


