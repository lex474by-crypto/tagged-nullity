def test_axioms_b():
    """Базовые аксиомы системы B."""
    assert b_div(1, 0) == NullB(1),                 "B1: 1/0 = ⊥(1)"
    assert b_div(0, 0) == 0,                        "B2: 0/0 = 0"
    assert b_sub(b_div(5, 0), b_div(5, 0)) == 0,    "B3: ⊥(5)−⊥(5) = ⊥(0) = 0"
    assert b_mul(3, b_div(2, 0)) == NullB(6),       "B4: 3×⊥(2) = ⊥(6)"
    assert b_mul(b_div(5, 0), 0) == 0,              "B5: ⊥(5)×0 = 0 (не возврат!)"
    assert extract(b_div(1, 0)) == 1,               "B6: extract(⊥(1)) = 1"
    assert b_add(b_div(5, 0), 10) == NullB(5),      "B7: ⊥(5)+10 = ⊥(5)"
    assert b_div(b_div(7, 0), 0) == NullB(7),       "B8: ⊥(7)/0 = ⊥(7)"
    # Конвенция: ⊥(x)/b = ⊥(x/b) для b ≠ 0 (линейность, как в B4)
    assert b_div(b_div(7, 0), 2) == NullB(3.5),     "⊥(7)/2 = ⊥(3.5)"
    print("[OK] Аксиомы системы B (B1–B8)")


def test_division_by_nullity_rejected():
    """Деление НА нулити запрещено: возврат метки — только через extract()."""
    try:
        b_div(1, b_div(2, 0))                       # 1 / ⊥(2)
        assert False, "1/⊥(2) не должно молча возвращать 0.5 (обход extract)"
    except ValueError:
        pass
    # Правильный путь: явная распаковка делителя — решение принимает человек
    assert b_div(1, extract(b_div(2, 0))) == 0.5
    print("[OK] Деление на нулити отклонено; extract(b) — единственный путь возврата")


def test_b_no_collapse():
    """Главное: в системе B вывод 2=1 невозможен — арифметика цела."""
    assert 2 * 1 == 2
    assert b_mul(2, b_mul(b_div(1, 0), 0)) == 0     # 2 × (⊥(1)×0) = 2×0 = 0 ≠ 1
    assert (2 + 3) * 4 == 2 * 4 + 3 * 4             # дистрибутивность цела
    print("[OK] Система B: коллапс 2=1 заблокирован, обычная алгебра работает")


def test_debugging_b():
    """Сценарий отладки: финансовая формула со скрытым делением на ноль."""
    # f = (активы − обязательства) / (объём − хедж) × курс + комиссия
    def f(act, liab, vol, hedge, rate, fee):
        return b_add(b_mul(b_div(b_sub(act, liab), b_sub(vol, hedge)), rate), fee)

    r = f(500, 120, 40, 40, 1.08, 15)               # vol == hedge → деление на 0
    assert isinstance(r, NullB)
    assert extract(r) == 380 * 1.08                 # метка выжила после ×курс и +комиссия
    assert "380/0" in trace(r)                      # трассировка указывает на источник
    print(f"[OK] Отладка: результат {r}, trace → {trace(r)}")
    print(f"     IEEE 754 дал бы молчаливый inf/nan без какой-либо локализации")


def test_collapse_c():
    """Система C: почему возврат-умножение требует отказа от ассоциативности."""
    one0 = c_div(num(1), num(0))                    # ¹⊥ = 1/0
    # С перестановкой скобок: 2 = 2×1 = 2×(¹⊥×0) = (2×0)×¹⊥ = 0×¹⊥ = 1
    left = c_mul(num(2), c_mul(one0, num(0)))       # 2×(¹⊥×0) = 2×1 = 2
    right = c_mul(c_mul(num(2), num(0)), one0)      # (2×0)×¹⊥ = 0×¹⊥ = 1
    assert left.val == 2 and right.val == 1
    print("[OK] Система C: 2×(¹⊥×0)=2, но (2×0)×¹⊥=1 — скобки нельзя трогать НИКОГДА")


def test_c_ambiguity():
    """Система C: одна строка '2×¹⊥×2×0', два значения."""
    one0 = c_div(num(1), num(0))
    v_author = c_mul(c_mul(num(2), one0), c_mul(num(2), num(0)))     # ((2×¹⊥)×(2×0))
    v_ltr = c_mul(c_mul(c_mul(num(2), one0), num(2)), num(0))        # слева направо
    assert v_author.val == 2, "прочтение автора концепции"
    assert v_ltr.val == 4, "прочтение слева направо"
    assert not v_author.same(v_ltr), "деревья различны → 'равенства' нет"
    print(f"[OK] Система C: '2×¹⊥×2×0' = {v_author.val} ИЛИ {v_ltr.val} "
          f"в зависимости от скобок; A.same(B) = False → unit-тест невозможен")


